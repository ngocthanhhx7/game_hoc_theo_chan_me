import { test, expect } from '@playwright/test';

test('MC: answers stay hidden until publication, points survive reload, results are reachable', async ({page}) => {
 await page.goto('/');
 await expect(page.getByRole('heading',{name:'Cùng Mẹ bước vào hành trình ánh sáng.',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Bắt Đầu Trình Chiếu',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Đoàn con quy tụ',exact:true})).toBeVisible();
 await expect(page.getByRole('textbox')).toHaveCount(2);
 await page.getByRole('button',{name:'Hoàn tất — Bắt đầu vòng 1',exact:true}).click();
 await expect(page.getByText('MAGNIFICAT',{exact:true})).toHaveCount(0);
 await page.getByRole('button',{name:'Bắt đầu · 30 giây',exact:true}).click();
 await page.getByRole('button',{name:'Khóa lượt trả lời',exact:true}).click();
 await expect(page.getByText('MAGNIFICAT',{exact:true})).toHaveCount(0);
 await page.getByRole('button',{name:'Công bố đáp án',exact:true}).click();
 await expect(page.getByText('MAGNIFICAT',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Chính xác (+10 điểm)',exact:true}).click();
 await page.getByRole('button',{name:'Vòng 2: Trắc nghiệm',exact:true}).click();
 await page.getByRole('button',{name:'Bắt đầu đếm giờ (20s)',exact:true}).click();
 await page.getByRole('button',{name:/^B Năm 1854; khẳng định ngay từ giây phút đầu tiên/}).click();
 await page.getByRole('button',{name:'Khóa đáp án B',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Đáp án B',exact:true})).toHaveCount(0);
 await page.getByRole('button',{name:'Công bố đáp án',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Đáp án B',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Vòng 3: Xin Vâng',exact:true}).click();
 await page.getByRole('button',{name:/01 Ai là cha mẹ của Đức Maria/}).click();
 await page.getByRole('button',{name:'Bắt đầu · 60 giây',exact:true}).click();
 await page.getByRole('button',{name:'Khóa lượt trả lời',exact:true}).click();
 await expect(page.getByText(/Thánh Gio-akim \(Joachim\)/)).toHaveCount(0);
 await page.getByRole('button',{name:'Công bố đáp án tham khảo',exact:true}).click();
 await page.getByRole('button',{name:'Đúng trọn vẹn (+20đ)',exact:true}).click();
 await expect(page.getByRole('button',{name:'Đúng trọn vẹn (+20đ)',exact:true})).toHaveCount(0);
 await page.getByRole('button',{name:'Bảng Điểm',exact:true}).click();
 const row=page.getByRole('row').filter({hasText:'Đội Sao Biển'});
 await expect(row).toContainText('50đ');
 await page.reload();
 await expect(page.getByRole('row').filter({hasText:'Đội Sao Biển'})).toContainText('50đ');
 await page.getByRole('button',{name:'Công Bố Kết Quả Chung Cuộc',exact:true}).click();
 await expect(page.getByText('VINH DANH QUÁN QUÂN CHUNG CUỘC',{exact:true})).toBeVisible();
});
